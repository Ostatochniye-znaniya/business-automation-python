const CheckBox: React.FC<CheckBoxProps> = ({
  text,
  state: externalState,
  type,
  onChange,
}) => {
  const [internalState, setInternalState] = useState(false);
  const [isDark, setIsDark] = useState(false);

  const isActive = externalState !== undefined ? externalState : internalState;

  useEffect(() => {
    const darkModeQuery = window.matchMedia("(prefers-color-scheme: dark)");
    setIsDark(darkModeQuery.matches);

    // Слушаем изменения системной темы
    const handler = (e: MediaQueryListEvent) => setIsDark(e.matches);
    darkModeQuery.addEventListener("change", handler);
    return () => darkModeQuery.removeEventListener("change", handler);
  }, []);

  const handleClick = () => {
    const newState = !isActive;
    if (externalState !== undefined && onChange) {
      onChange(newState);
    } else {
      setInternalState(newState);
    }
  };

  return (
    <label className="cb-container">
      <button
        className={`${isActive ? `cb-block-active-${type}` : "cb-block-deactive"} cb-block`}
        type="button"
        onClick={handleClick}
      >
        {isActive ? getCheckIcon(type, isDark) : <></>}
      </button>
      {text && <p className="cb-text">{text}</p>}
    </label>
  );
};

export default CheckBox;
